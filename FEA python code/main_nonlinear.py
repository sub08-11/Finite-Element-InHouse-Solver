def write_vtk_custom(filepath, nodes, conn, u_disp, field_data={}):
    n_nodes = len(nodes); n_elems = len(conn); dim = nodes.shape[1]
    npe = len(conn[0]); cell_type = 0
    if dim == 2:
        if npe == 3: cell_type = 5
        elif npe == 4: cell_type = 9
        elif npe == 6: cell_type = 22
        elif npe == 8: cell_type = 23
    elif dim == 3:
        if npe == 4: cell_type = 10
        elif npe == 8: cell_type = 12
        elif npe == 10: cell_type = 24
        elif npe == 20: cell_type = 25

    with open(filepath, 'w') as f:
        f.write("# vtk DataFile Version 3.0\nGenerated by NonlinearHyper\nASCII\nDATASET UNSTRUCTURED_GRID\n")
        f.write(f"POINTS {n_nodes} double\n")
        for i in range(n_nodes):
            x, y = nodes[i, 0], nodes[i, 1]
            z = nodes[i, 2] if dim == 3 else 0.0
            f.write(f"{x:.6f} {y:.6f} {z:.6f}\n")
        f.write(f"\nCELLS {n_elems} {n_elems * (npe + 1)}\n")
        for c in conn: f.write(f"{npe} " + " ".join(map(str, c)) + "\n")
        f.write(f"\nCELL_TYPES {n_elems}\n")
        for _ in range(n_elems): f.write(f"{cell_type}\n")
        
        f.write(f"\nPOINT_DATA {n_nodes}\n")
        f.write("VECTORS Displacement double\n")
        for i in range(n_nodes):
            ux, uy = u_disp[i, 0], u_disp[i, 1]
            uz = u_disp[i, 2] if u_disp.shape[1] == 3 else 0.0
            f.write(f"{ux:.6e} {uy:.6e} {uz:.6e}\n")
            
        for name, data in field_data.items():
            if len(data) == n_nodes:
                f.write(f"\nSCALARS {name} double 1\nLOOKUP_TABLE default\n")
                for val in data: f.write(f"{val:.6e}\n")

