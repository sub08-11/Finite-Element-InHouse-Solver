def _make_traction_edges_2d(setting, NL, conn): 
    traction_list = getattr(setting, "traction_list_3d", [])
    if not traction_list: return []
    edge_defs = [(0,1,4),(1,2,5),(2,3,6),(3,0,7)] if len(conn[0])==8 else [(0,1,None),(1,2,None),(2,3,None),(3,0,None)]
    if len(conn[0]) == 3: edge_defs = [(0,1,None),(1,2,None),(2,0,None)]

    edges = []
    for it in traction_list:
        ns = set(n-1 if 0 not in it["nodes"] else n for n in it["nodes"])
        T = it.get("traction", [0,0,0])[:2]
        P = it.get("pressure", None)
        for e_idx, c in enumerate(conn):
            for n1,n2,m in edge_defs:
                if n1 < len(c) and n2 < len(c) and c[n1] in ns and c[n2] in ns:
                    data = {"element": e_idx}
                    if m is not None and m < len(c): data["nodes3"] = (c[n1]+1,c[m]+1,c[n2]+1)
                    else: data["nodes"] = (c[n1]+1,c[n2]+1)
                    if P is not None: data["pressure"] = P
                    else: data["T"] = T
                    edges.append(data)
    return edges

def _make_traction_faces_3d(setting, NL, conn):
    """
    Splits node list into element faces for 3D integration (Hex/Tet).
    """
    traction_list = getattr(setting, "traction_list_3d", [])
    if not traction_list: return []
    
    npe = len(conn[0])
    
    # Define Face Topology
    if npe >= 8: # Hex
        face_defs = [
            (0,1,2,3), (4,5,6,7), 
            (0,1,5,4), (1,2,6,5), 
            (2,3,7,6), (3,0,4,7)
        ]
    elif npe >= 4: # Tet
        face_defs = [
            (0,1,2), (0,3,1), (1,3,2), (2,3,0)
        ]
    else:
        return []

    faces = []
    for it in traction_list:
        # Convert user input nodes (1-based) to 0-based set for check
        ns = set(n-1 for n in it["nodes"])
        
        val_t = it.get("traction", None)
        val_p = it.get("pressure", None)
        
        for e_idx, c in enumerate(conn):
            for f_nodes_idx in face_defs:
                # Global node IDs for this face
                face_global_ids = [c[idx] for idx in f_nodes_idx]
                
                # If all nodes of this face are in the traction set
                if all(nid in ns for nid in face_global_ids):
                    data = {
                        "nodes": [n+1 for n in face_global_ids], # 1-based for Solver
                        "element": e_idx
                    }
                    if val_p is not None: 
                        data["type"] = "pressure"
                        data["value"] = val_p
                    else: 
                        data["type"] = "traction"
                        data["value"] = val_t if val_t else [0,0,0]
                    faces.append(data)
    return faces


