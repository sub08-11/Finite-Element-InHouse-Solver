def _enu_to_mu_lam(E: float, nu: float) -> Tuple[float, float]:
    mu = E / (2.0 * (1.0 + nu))
    if abs(nu - 0.5) < 1e-9: lam = 1e8 * mu 
    else: lam = E * nu / ((1.0 + nu) * (1.0 - 2.0 * nu))
    return float(mu), float(lam)

