def run_hyperelastic_analysis(setting):
    # 1. Mesh 로드 및 초기 설정
    mesh = Mesh.from_inp(getattr(setting, "inp_path", ""), debug=False)
    NL, conn = mesh.NL, np.asarray(mesh.conn, int)
    # 1-based 인덱싱 보정
    if np.min(conn) == 1: conn = conn - 1
    dim = NL.shape[1]
    
    print(f"\n[RUN] Nonlinear Hyperelastic Analysis ({dim}D)")
    print(f"[RUN] Mesh: {len(NL)} nodes, {len(conn)} elements")
    
    mu, lam = _enu_to_mu_lam(float(setting.E), float(setting.nu))
    sf = Shape_Function(None, setting.element_order, setting.element_shape, setting.integration)
    
    # Plane Stress 확인 및 로그 출력
    is_plane_stress = (getattr(setting, "analytical_conditions", "").lower().strip() == "plane stress")
    
    if dim == 2:
        if is_plane_stress:
            print("  - Condition: Plane Stress")
        else:
            print("  - Condition: Plane Strain")
    else:
        print("  - Condition: 3D Continuum")

    # 2. 비선형 모델 객체 생성
    model = NonlinearHyper(NL, conn, setting.element_shape, setting.element_order, setting.integration,
                           float(setting.thickness), sf, {"mu":mu,"lam":lam}, is_plane_stress, dim=dim)

    # -------------------------------------------------------------
    # [핵심 수정] 경계조건 분리 로드 및 통합
    # -------------------------------------------------------------
    
    # (1) 고정 조건 (0.0) 로드
    dirichlet_fixed = {}
    for it in getattr(setting, "dirichlet_list_3d", []):
        dirichlet_fixed[int(it[0])] = tuple(it[1:])

    # (2) 강제 변위 조건 (Not 0.0) 로드
    dirichlet_disp = {}
    for it in getattr(setting, "displacement_list_3d", []):
        dirichlet_disp[int(it[0])] = tuple(it[1:])

    # (3) 로그 출력 (사용자 확인용으로 분리해서 보여줌)
    print(f"  - Dirichlet BCs (fixed): {len(dirichlet_fixed)} nodes")
    print(f"  - Prescribed displacement BCs: {len(dirichlet_disp)} nodes")

    # (4) 솔버 입력용 통합 (NonlinearHyper는 하나의 딕셔너리로 처리하므로 합침)
    # ** 주의: 키가 겹칠 경우 뒤에 오는 dirichlet_disp 값이 우선 적용됨
    solver_dirichlet_input = {**dirichlet_fixed, **dirichlet_disp}
    # -------------------------------------------------------------

    # Traction / Body Force 처리
    if dim == 2: 
        tr_data = _make_traction_edges_2d(setting, NL, conn)
        b0 = getattr(setting, "body_force_vec_2d", (0,0))
    else: 
        tr_data = _make_traction_faces_3d(setting, NL, conn)
        b0 = getattr(setting, "body_force_vec_3d", (0,0,0))
        
    print(f"  - Traction/Pressure Items: {len(tr_data)} faces/edges generated.")

    # 집중 하중 처리
    conc = []
    for it in getattr(setting, "concentrated_force_list_3d", []):
        for n in it["nodes"]: 
            conc.append({"node": n, "F": it["F"]})
    
    # 3. 솔버 실행
    # [중요] 첫 번째 인자로 통합된 'solver_dirichlet_input'을 전달합니다.
    u = model.solve(
        solver_dirichlet_input,
        int(getattr(setting, "nsteps", 20)),
        float(getattr(setting, "atol", 1e-8)),
        float(getattr(setting, "rtol", 1e-8)),
        float(getattr(setting, "stol", 1e-8)),
        int(getattr(setting, "max_iter", 60)),
        b0,
        tr_data,
        conc,
        verbose=True,
        mode=str(getattr(setting, "nonlinear_mode", "fenics")),
        adapt_steps=bool(getattr(setting, "adaptive", False)),
    )

    # 4. 후처리 및 VTK 저장
    print("[VTK] Calculating Stresses...")
    _, S_nodes = model.compute_postprocessing_stresses(u)
    
    field_data = {}
    U_vec = np.column_stack([u[0::dim], u[1::dim], u[2::dim]]) if dim==3 else np.column_stack([u[0::2], u[1::2], np.zeros(len(NL))])
    field_data["UMAG"] = np.linalg.norm(U_vec, axis=1)
    
    if dim == 2:
        field_data["S11"], field_data["S22"], field_data["S33"], field_data["S12"] = S_nodes[:,0], S_nodes[:,1], S_nodes[:,2], S_nodes[:,3]
        field_data["Mises"] = S_nodes[:,4]
    else:
        field_data["S11"], field_data["S22"], field_data["S33"] = S_nodes[:,0], S_nodes[:,1], S_nodes[:,2]
        field_data["S12"], field_data["S13"], field_data["S23"] = S_nodes[:,3], S_nodes[:,4], S_nodes[:,5]
        field_data["Mises"] = S_nodes[:,6]

    out_dir = os.path.join(os.getcwd(), "results"); os.makedirs(out_dir, exist_ok=True)
    vtk_path = os.path.join(out_dir, getattr(setting, "vtk_filename", "result.vtk"))
    write_vtk_custom(vtk_path, NL, conn, U_vec, field_data)
    print(f"[VTK] Saved: {vtk_path}")
    
    if getattr(setting, "auto_open_paraview", True):
        try: open_in_paraview(vtk_path)
        except: pass

